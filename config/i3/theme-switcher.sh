#!/usr/bin/env bash

set -euo pipefail

readonly I3_DIR="/home/coisini/.config/i3"
readonly THEMES_DIR="$I3_DIR/themes"
readonly CURRENT_DIR="$THEMES_DIR/current"
readonly STATE_FILE="$I3_DIR/.current-theme"
readonly POLYBAR_CONFIG="/home/coisini/.config/polybar/config.ini"
readonly POLYBAR_LAUNCH="/home/coisini/.config/polybar/launch.sh"
readonly TRAY_APPLETS_LAUNCH="$I3_DIR/tray-applets-launch.sh"
readonly KITTY_CONF="/home/coisini/.config/kitty/kitty.conf"
SKIP_LIVE_POLYBAR="${SKIP_LIVE_POLYBAR:-1}"

die() {
  echo "theme-switcher: $*" >&2
  exit 1
}

theme_dir_for() {
  local id="$1"
  [[ "$id" =~ ^[A-Za-z0-9_-]+$ ]] || die "bad theme id: $id"
  echo "$THEMES_DIR/$id"
}

load_theme() {
  THEME_ID="$1"
  THEME_DIR="$(theme_dir_for "$THEME_ID")"
  [[ -f "$THEME_DIR/theme.conf" ]] || die "missing theme.conf for $THEME_ID"

  # shellcheck source=/dev/null
  source "$THEME_DIR/theme.conf"

  THEME_LABEL="${THEME_LABEL:-$THEME_ID}"
  THEME_ICON="${THEME_ICON:-}"
  WALLPAPER="${WALLPAPER:-wallpaper.png}"

  BAR_BG="${BAR_BG:-#dcd3ca}"
  BG_ALT="${BG_ALT:-#c9bfb4}"
  PANEL="${PANEL:-#f5ebe1}"
  PANEL_ALT="${PANEL_ALT:-#d0c6ba}"
  INK="${INK:-#1a1a1a}"
  INK_SOFT="${INK_SOFT:-#2a2a2a}"
  MUTED="${MUTED:-#6a6258}"
  MUTED_SOFT="${MUTED_SOFT:-#b3a99c}"
  WHITE="${WHITE:-#ffffff}"
  ACCENT="${ACCENT:-#ca7081}"
  ACCENT_SOFT="${ACCENT_SOFT:-$ACCENT}"
  CYAN="${CYAN:-#4f8a82}"
  AQUA="${AQUA:-#6f8f6f}"
  GREEN="${GREEN:-#6f8f6f}"
  YELLOW="${YELLOW:-#b08a4a}"
  ORANGE="${ORANGE:-#c07a4a}"
  PURPLE="${PURPLE:-#9a6f8a}"
  RED="${RED:-$ACCENT}"
  LOCK_BG="${LOCK_BG:-$PANEL}"

  [[ -f "$THEME_DIR/$WALLPAPER" ]] || die "missing wallpaper: $THEME_DIR/$WALLPAPER"
}

theme_entries() {
  local dir id label icon wallpaper
  for dir in "$THEMES_DIR"/*; do
    [[ -d "$dir" ]] || continue
    [[ "$(basename "$dir")" == "current" ]] && continue
    [[ -f "$dir/theme.conf" ]] || continue
    id="$(basename "$dir")"
    (
      # shellcheck source=/dev/null
      source "$dir/theme.conf"
      label="${THEME_LABEL:-$id}"
      icon="${THEME_ICON:-}"
      wallpaper="${WALLPAPER:-wallpaper.png}"
      [[ -f "$dir/$wallpaper" ]] || exit 0
      printf '%s\t%s %s\n' "$id" "$icon" "$label"
    )
  done | sort
}

current_theme() {
  if [[ -f "$STATE_FILE" ]]; then
    cat "$STATE_FILE"
    return
  fi

  echo "beige"
}

prepare_current_dir() {
  if [[ -L "$CURRENT_DIR" ]]; then
    rm -f "$CURRENT_DIR"
  fi
  mkdir -p "$CURRENT_DIR"
}

