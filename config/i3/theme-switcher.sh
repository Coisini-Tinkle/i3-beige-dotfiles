render_polybar_config() {
  [[ -f "$POLYBAR_CONFIG" ]] || return 0

  local tmp menu_content
  tmp="$(mktemp)"
  menu_content="%{T4}%{F$INK}%{F-}%{T-}%{T1}%{B$INK}%{F$PANEL} 󰣛 %{F-}%{B-}%{T-}%{T4}%{F$INK}%{F-}%{T-}"

  awk \
    -v bg="$BAR_BG" -v bg_alt="$BG_ALT" -v fg="$INK" -v dim="$MUTED" \
    -v ink="$INK" -v cream="$PANEL" -v cyan="$CYAN" -v aqua="$AQUA" \
    -v green="$GREEN" -v yellow="$YELLOW" -v orange="$ORANGE" \
    -v red="$RED" -v purple="$PURPLE" -v menu="$menu_content" '
      /^\[colors\]$/ {
        print
        print "background = " bg
        print "background-alt = " bg_alt
        print "foreground = " fg
        print "foreground-dim = " dim
        print "ink = " ink
        print "cream = " cream
        print "cyan = " cyan
        print "aqua = " aqua
        print "green = " green
        print "yellow = " yellow
        print "orange = " orange
        print "red = " red
        print "purple = " purple
        in_colors = 1
        next
      }
      in_colors && /^\[/ { in_colors = 0 }
      in_colors { next }
      /^\[module\/menu\]$/ { in_menu = 1; print; next }
      /^\[module\// && !/^\[module\/menu\]$/ { in_menu = 0; print; next }
      in_menu && /^content = / { print "content = " menu; next }
      { print }
    ' "$POLYBAR_CONFIG" > "$tmp"

  mv "$tmp" "$POLYBAR_CONFIG"
}

ensure_kitty_include() {
  [[ -f "$KITTY_CONF" ]] || return 0

  if grep -q '^include /home/coisini/.config/i3/themes/current/kitty.conf$' "$KITTY_CONF"; then
    return 0
  fi

  if grep -q '^include /home/coisini/.config/i3/themes/beige/kitty-beige.conf$' "$KITTY_CONF"; then
    sed -i 's|^include /home/coisini/.config/i3/themes/beige/kitty-beige.conf$|include /home/coisini/.config/i3/themes/current/kitty.conf|' "$KITTY_CONF"
  else
    printf '\ninclude /home/coisini/.config/i3/themes/current/kitty.conf\n' >> "$KITTY_CONF"
  fi
}

stop_tray_clients() {
  pkill -x nm-applet 2>/dev/null || true
  pkill -x pasystray 2>/dev/null || true
  pkill -x blueman-applet 2>/dev/null || true
  pkill -x cc-switch 2>/dev/null || true
  pkill -f '^/usr/bin/python3 /usr/bin/ulauncher --hide-window' 2>/dev/null || true
  pgrep -f '^/opt/todesk/bin/ToDesk$' | xargs -r kill -9 2>/dev/null || true
  sleep 0.2
}

start_tray_clients() {
  if command -v cc-switch >/dev/null 2>&1; then
    /usr/bin/cc-switch >/tmp/cc-switch.log 2>&1 &
    sleep 0.4
  fi
  if command -v ulauncher >/dev/null 2>&1; then
    /usr/bin/ulauncher --hide-window --hide-window >/tmp/ulauncher.log 2>&1 &
    sleep 0.4
  fi
  if command -v nm-applet >/dev/null 2>&1; then
    /usr/bin/dbus-launch nm-applet --sm-disable >/tmp/nm-applet.log 2>&1 &
    sleep 0.4
  fi
  if command -v pasystray >/dev/null 2>&1; then
    pasystray >/tmp/pasystray.log 2>&1 &
    sleep 0.4
  fi
  if command -v blueman-applet >/dev/null 2>&1; then
    blueman-applet >/tmp/blueman-applet.log 2>&1 &
    sleep 0.4
  fi
}

stop_polybar() {
  pkill -x polybar 2>/dev/null || true
  pgrep -f '^/bin/sh -c ~/.config/polybar/scripts/i3-workspaces.sh$|^bash /home/coisini/.config/polybar/scripts/i3-workspaces.sh$' \
    | xargs -r kill 2>/dev/null || true
}

launch_polybar() {
  [[ -x "$POLYBAR_LAUNCH" ]] || return 0

  if command -v i3-msg >/dev/null 2>&1; then
    i3-msg "exec --no-startup-id bash $POLYBAR_LAUNCH" >/tmp/polybar-theme-switch.log 2>&1 || true
    return 0
  fi

  bash "$POLYBAR_LAUNCH" >/tmp/polybar-theme-switch.log 2>&1 || true
}

launch_tray_clients() {
  if [[ -x "$TRAY_APPLETS_LAUNCH" ]] && command -v i3-msg >/dev/null 2>&1; then
    i3-msg "exec --no-startup-id $TRAY_APPLETS_LAUNCH" >/tmp/tray-applets-theme-switch.log 2>&1 || true
    return 0
  fi

  if [[ -x "$TRAY_APPLETS_LAUNCH" ]]; then
    "$TRAY_APPLETS_LAUNCH" >/tmp/tray-applets-theme-switch.log 2>&1 || true
    return 0
  fi

  start_tray_clients
}

hide_todesk_windows() {
  command -v jq >/dev/null 2>&1 || return 0
  i3-msg -t get_tree \
    | jq -r '.. | objects | select(.window_properties.class? == "ToDesk") | .id' \
    | while read -r con_id; do
        [[ -n "$con_id" ]] && i3-msg "[con_id=\"$con_id\"] move scratchpad" >/dev/null 2>&1 || true
      done
}

apply_wallpaper_with_bar_restart() {
  stop_tray_clients
  stop_polybar

  if command -v feh >/dev/null 2>&1; then
    feh --no-fehbg --bg-fill "$CURRENT_DIR/wallpaper.png" || true
  fi

  launch_polybar
  sleep 1
  launch_tray_clients
  sleep 1
  hide_todesk_windows
}

apply_theme() {
  load_theme "$1"

  render_i3_colors
  render_kitty_conf
  render_control_center_css
  render_music_panel_css
  if [[ "$SKIP_LIVE_POLYBAR" != "1" ]]; then
    render_polybar_config
  fi
  ensure_kitty_include

  prepare_current_dir
  cp -f "$THEME_DIR/theme.conf" "$CURRENT_DIR/theme.conf"
  cp -f "$THEME_DIR/$WALLPAPER" "$CURRENT_DIR/wallpaper.png"
  cp -f "$THEME_DIR/i3-colors.conf" "$CURRENT_DIR/i3-colors.conf"
  cp -f "$THEME_DIR/kitty.conf" "$CURRENT_DIR/kitty.conf"
  printf '%s\n' "$THEME_ID" > "$STATE_FILE"

  if [[ "${APPLY_THEME_WALLPAPER:-1}" == "1" ]]; then
    apply_wallpaper_with_bar_restart
  fi

  if [[ "${APPLY_THEME_KITTY_SIGNAL:-1}" == "1" ]]; then
    pkill -USR1 kitty 2>/dev/null || true
  fi

  echo "$THEME_ID"
}

show_menu() {
  command -v rofi >/dev/null 2>&1 || die "rofi not found"

  local selected id
  selected="$(theme_entries | rofi -dmenu -i -p "Theme" \
    -theme-str 'listview { lines: 8; }' 2>/dev/null || true)"
  [[ -z "$selected" ]] && exit 0

  id="${selected%%$'\t'*}"
  apply_theme "$id"
}

case "${1:-menu}" in
  menu)
    show_menu
    ;;
  apply|set)
    apply_theme "${2:-}"
    ;;
  current)
    current_theme
    ;;
  list)
    theme_entries
    ;;
  render-polybar)
    load_theme "$(current_theme)"
    render_polybar_config
    ;;
  *)
    echo "usage: $0 [menu|list|current|apply THEME_ID]" >&2
    exit 2
    ;;
esac
